import XCTest
@testable import MindBusCore

final class ClaudeCodeLoaderParseLineTests: XCTestCase {
    func testParseUserMessageStringContent() {
        let line = #"{"type":"user","message":{"role":"user","content":"hello"},"uuid":"u-1","timestamp":"2026-04-07T11:20:40.328Z"}"#
        let msg = ClaudeCodeLoader.parseLine(line)
        XCTAssertNotNil(msg)
        XCTAssertEqual(msg?.id, "u-1")
        XCTAssertEqual(msg?.role, .user)
        XCTAssertEqual(msg?.blocks.count, 1)
        if case .text(let t) = msg?.blocks.first {
            XCTAssertEqual(t, "hello")
        } else {
            XCTFail("expected text block")
        }
    }

    // MARK: - 噪音过滤（工具输出 / 注入脚手架）

    func testPureToolResultMessageDropped() {
        let line = #"{"type":"user","message":{"role":"user","content":[{"type":"tool_result","content":"command output"}]},"uuid":"u","timestamp":"2026-04-07T11:20:40.328Z"}"#
        XCTAssertNil(ClaudeCodeLoader.parseLine(line))
    }

    func testTaskNotificationMessageDropped() {
        let line = #"{"type":"user","message":{"role":"user","content":"<task-notification>\n<task-id>x</task-id>"},"uuid":"u","timestamp":"2026-04-07T11:20:40.328Z"}"#
        XCTAssertNil(ClaudeCodeLoader.parseLine(line))
    }

    func testSkillScaffoldingDropped() {
        let line = #"{"type":"user","message":{"role":"user","content":"Base directory for this skill: /Users/x/.claude/skills/foo\n\n# Foo"},"uuid":"u","timestamp":"2026-04-07T11:20:40.328Z"}"#
        XCTAssertNil(ClaudeCodeLoader.parseLine(line))
    }

    func testSlashCommandScaffoldingDropped() {
        let line = #"{"type":"user","message":{"role":"user","content":"<command-name>/model</command-name>\n<command-message>model</command-message>"},"uuid":"u","timestamp":"2026-04-07T11:20:40.328Z"}"#
        XCTAssertNil(ClaudeCodeLoader.parseLine(line))
    }

    func testLocalCommandCaveatDropped() {
        let line = #"{"type":"user","message":{"role":"user","content":"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>"},"uuid":"u","timestamp":"2026-04-07T11:20:40.328Z"}"#
        XCTAssertNil(ClaudeCodeLoader.parseLine(line))
    }

    func testSystemReminderStrippedKeepsRealText() {
        let line = #"{"type":"user","message":{"role":"user","content":"帮我改这个\n<system-reminder>\nbig injected ctx\n</system-reminder>"},"uuid":"u","timestamp":"2026-04-07T11:20:40.328Z"}"#
        if case .text(let t) = ClaudeCodeLoader.parseLine(line)?.blocks.first {
            XCTAssertEqual(t, "帮我改这个")
        } else { XCTFail("应保留真实文字、剥离 system-reminder") }
    }

    func testToolResultDroppedButTextKept() {
        let line = #"{"type":"user","message":{"role":"user","content":[{"type":"text","text":"看这个结果"},{"type":"tool_result","content":"raw output"}]},"uuid":"u","timestamp":"2026-04-07T11:20:40.328Z"}"#
        let msg = ClaudeCodeLoader.parseLine(line)
        XCTAssertEqual(msg?.blocks.count, 1)
        if case .text(let t) = msg?.blocks.first { XCTAssertEqual(t, "看这个结果") } else { XCTFail() }
    }

    func testParseAssistantMessageArrayContentWithText() {
        let line = #"{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"ok"}]},"uuid":"a-1","timestamp":"2026-04-07T11:20:47.555Z"}"#
        let msg = ClaudeCodeLoader.parseLine(line)
        XCTAssertEqual(msg?.role, .assistant)
        if case .text(let t) = msg?.blocks.first {
            XCTAssertEqual(t, "ok")
        } else {
            XCTFail("expected text block")
        }
    }

    func testParseAssistantMessageWithToolUsePreservesAsBlock() {
        let line = #"{"type":"assistant","message":{"role":"assistant","content":[{"type":"tool_use","id":"t1","name":"Bash","input":{"command":"ls"}}]},"uuid":"a-2","timestamp":"2026-04-07T11:21:00.000Z"}"#
        let msg = ClaudeCodeLoader.parseLine(line)
        XCTAssertEqual(msg?.blocks.count, 1)
        if case .toolUse(let name, let input) = msg?.blocks.first {
            XCTAssertEqual(name, "Bash")
            XCTAssertTrue(input.contains("ls"))
        } else {
            XCTFail("expected toolUse block")
        }
    }

    func testParseReturnsNilForUnknownType() {
        let line = #"{"type":"system","message":{"role":"system","content":"x"},"uuid":"s-1","timestamp":"2026-04-07T11:00:00.000Z"}"#
        XCTAssertNil(ClaudeCodeLoader.parseLine(line))
    }

    func testParseReturnsNilForMissingUuid() {
        let line = #"{"type":"user","message":{"role":"user","content":"x"},"timestamp":"2026-04-07T11:00:00.000Z"}"#
        XCTAssertNil(ClaudeCodeLoader.parseLine(line))
    }

    func testParseReturnsNilForInvalidJson() {
        XCTAssertNil(ClaudeCodeLoader.parseLine("not json"))
        XCTAssertNil(ClaudeCodeLoader.parseLine(""))
    }

    func testParseAssistantMessageWithThinkingBlock() {
        let line = #"{"type":"assistant","message":{"role":"assistant","content":[{"type":"thinking","thinking":"让我想想..."}]},"uuid":"t-1","timestamp":"2026-04-07T11:20:00.000Z"}"#
        let msg = ClaudeCodeLoader.parseLine(line)
        XCTAssertEqual(msg?.blocks.count, 1)
        if case .thinking(let t) = msg?.blocks.first {
            XCTAssertEqual(t, "让我想想...")
        } else {
            XCTFail("expected thinking block")
        }
    }

    func testParseUserMessageWithBase64Image() {
        let line = #"{"type":"user","message":{"role":"user","content":[{"type":"image","source":{"type":"base64","media_type":"image/png","data":"abc"}}]},"uuid":"i-1","timestamp":"2026-04-07T11:20:00.000Z"}"#
        let msg = ClaudeCodeLoader.parseLine(line)
        XCTAssertEqual(msg?.blocks.count, 1)
        if case .image(let m, let src) = msg?.blocks.first {
            XCTAssertEqual(m, "image/png")
            XCTAssertEqual(src, .base64("abc"))
        } else {
            XCTFail("expected image block")
        }
    }

    func testParseUserMessageWithURLImage() {
        let line = #"{"type":"user","message":{"role":"user","content":[{"type":"image","source":{"type":"url","media_type":"image/jpeg","url":"https://e.com/x.jpg"}}]},"uuid":"i-2","timestamp":"2026-04-07T11:20:00.000Z"}"#
        let msg = ClaudeCodeLoader.parseLine(line)
        XCTAssertEqual(msg?.blocks.count, 1)
        if case .image(let m, let src) = msg?.blocks.first {
            XCTAssertEqual(m, "image/jpeg")
            XCTAssertEqual(src, .url("https://e.com/x.jpg"))
        } else {
            XCTFail("expected image block")
        }
    }

    func testParseImageWithoutSourceTypeFallsBackToUnknown() {
        let line = #"{"type":"user","message":{"role":"user","content":[{"type":"image","source":{"media_type":"image/webp"}}]},"uuid":"i-3","timestamp":"2026-04-07T11:20:00.000Z"}"#
        let msg = ClaudeCodeLoader.parseLine(line)
        XCTAssertEqual(msg?.blocks.count, 1)
        if case .image(let m, let src) = msg?.blocks.first {
            XCTAssertEqual(m, "image/webp")
            XCTAssertEqual(src, .unknown)
        } else {
            XCTFail("expected image block")
        }
    }
}
